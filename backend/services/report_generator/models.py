    spill_location: str

    detection_time: str

    spill_detected: bool

    confidence: float

    spill_area: float

    risk_score: int

    risk_level: str

    # ==========================================================
    # WEATHER
    # ==========================================================

    weather: dict

    # ==========================================================
    # DRIFT
    # ==========================================================

    drift_prediction: dict

    # ==========================================================
    # ENVIRONMENT
    # ==========================================================

    environmental_summary: dict

    # ==========================================================
    # AIS
    # ==========================================================

    suspected_vessel: dict

    # ==========================================================
    # ECONOMIC
    # ==========================================================

    economic_summary: dict

    # ==========================================================
    # CLEANUP
    # ==========================================================

    recommendations: list